"""Generates docs/MOVES.md from data/fighters/<id>.json (frame data is derived, never typed by hand).
Usage: python tools/moves_doc.py [id]    The box editor test (tests/test_moves_doc.gd) parses the table this writes."""
import json, sys
fid = sys.argv[1] if len(sys.argv) > 1 else "placeholder"
d = json.load(open(f"data/fighters/{fid}.json"))
CLIPS = {"L": "Punch_Jab", "M": "Punch_Cross", "H": "Melee_Hook", "S": "OverhandThrow", "throw": "OverhandThrow",
         "2L": "Punch_Jab", "2M": "Punch_Cross", "2H": "Melee_Hook", "jL": "Punch_Jab", "jM": "Punch_Cross", "jH": "Melee_Hook"}
NAMES = {"L": "Light", "M": "Medium", "H": "Heavy", "S": "Special (placeholder)", "throw": "Throw",
         "2L": "Crouch light", "2M": "Crouch medium", "2H": "Crouch heavy", "jL": "Jump light", "jM": "Jump medium", "jH": "Jump heavy"}
rows = []
for k, m in d["moves"].items():
    total = m["startup"] + m["active"] + m["recovery"]
    if m["kind"] == "throw":
        rows.append(f"| {k} | {NAMES[k]} | {m['startup']} | {m['active']} | {m['recovery']} | {m['dmg']} | throw | n/a | n/a | knockdown | {CLIPS[k]} |")
        continue
    h = m["hits"][0]
    rem = m["active"] + m["recovery"] - 1          # attacker frames left after the first active frame connects
    adv_h = h["hitstun"] - rem; adv_b = h["blockstun"] - rem
    kd = {"none": "-", "soft": "soft KD"}.get(h["kd"], h["kd"])
    rows.append(f"| {k} | {NAMES[k]} | {m['startup']} | {m['active']} | {m['recovery']} | {h['dmg']} | {h['level']} | {adv_h:+d} | {adv_b:+d} | {kd} | {CLIPS[k]} |")
out = f"""# MOVES: {d['name']} (placeholder fighter)

Draft for orchestrator review. Generated by `tools/moves_doc.py` from `data/fighters/{fid}.json`; do not edit the table by hand, change the data and regenerate. `tests/test_moves_doc.gd` checks that startup, active and recovery derived from the data match this table (and, once the box editor saves boxes, from the saved boxes) within 1 tick.

Timing is in sim ticks at 60 Hz. Startup is the number of ticks before the first active tick; the hit connects on the first active tick. On-hit and on-block advantage are measured from that first active tick: `stun - (active + recovery - 1)`. Level: mid hits either guard; low needs crouch guard; overhead needs standing guard (jump attacks are the only overheads).

| Move | Name | Startup | Active | Recovery | Damage | Level | On hit | On block | Result | Clip |
|---|---|---|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + """

## Notes
- Chain rules (from data `cancels`): L, M, 2L and 2M chain into heavier normals; L and M cancel into S. H, S, throw and air normals do not cancel.
- Clips are placeholders from Quaternius UAL (punches only; UAL has no kicks). Kicks, uppercut and real blocks wait for the Mixamo or alternative clip set, then the clip column changes and the timings are re-authored with the box editor.
- Air normals add 3 ticks of landing lag (`land_lag`).
- The throw is a close-range grab (range 46) that knocks down. It has no hitstop; the damage lands on the 8th tick after the grab. The defender can tech by pressing Throw on ticks 1 to 7 after the grab: no damage, both slide about 28 px apart, neutral after 20 ticks. Two throws on the same tick tech each other.
- 2H is a sweep: low, hard knockdown, -9 on block.
"""
open("docs/MOVES.md", "w", encoding="utf-8").write(out)
print(out)
